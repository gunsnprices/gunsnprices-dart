// Generates lib/src/data/*.g.dart from the JSON data in tool/data/.
//
// tool/data/models.json and tool/data/calibers.json are copies of the data
// files of the Python package (src/gunsnprices/data/); tool/data/entities.json
// is Python's HTML entity table (html.entities.html5 and the invalid
// character reference tables of html.unescape).
//
//   dart run tool/generate_data.dart && dart format lib
//
// The data is compiled into the package as Dart constants, so it works on
// every platform (VM, Flutter, web) without reading files at runtime.
import 'dart:convert';
import 'dart:io';

const _header =
    '// GENERATED by tool/generate_data.dart from tool/data/%s. Do not edit.\n'
    '// Data: CC BY 4.0, GunsNPrices (https://gunsnprices.com). See LICENSE-DATA.\n';

void main(List<String> args) {
  final root = args.isNotEmpty ? args.first : '.';
  final src = '$root/tool/data';
  final out = '$root/lib/src/data';
  _write('$out/calibers.g.dart', _calibers(_read('$src/calibers.json')));
  _write('$out/models.g.dart', _models(_read('$src/models.json')));
  _write('$out/entities.g.dart', _entities(_read('$src/entities.json')));
}

Map<String, dynamic> _read(String path) =>
    jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;

void _write(String path, String code) {
  File(path).writeAsStringSync(code);
  stdout.writeln('$path: ${code.length ~/ 1024} KB');
}

String _calibers(Map<String, dynamic> data) {
  final b = StringBuffer(_header.replaceFirst('%s', 'calibers.json'))
    ..writeln("import '../types.dart';")
    ..writeln("import 'schema.dart';")
    ..writeln()
    ..writeln('/// The GunsNPrices caliber list.')
    ..writeln('const caliberRecords = <CaliberRecord>[');
  for (final c in (data['calibers'] as List).cast<Map<String, dynamic>>()) {
    final url = (c['url'] as String?) ?? '';
    b
      ..writeln('  CaliberRecord(')
      ..writeln('    Caliber(')
      ..writeln('      id: ${_lit(c['id'] as String)},')
      ..writeln('      name: ${_lit(c['name'] as String)},')
      ..writeln('      type: CaliberType.${c['type']},')
      ..writeln(url.isEmpty ? '' : '      url: ${_lit(url)},')
      ..writeln('    ),')
      ..writeln('    siteName: ${_lit(c['site_name'] as String)},')
      ..writeln('    aliases: ${_list(c['aliases'])},')
      ..writeln('    n: ${(c['n'] as int?) ?? 0},')
      ..writeln('  ),');
  }
  b.writeln('];');
  return b.toString().replaceAll('\n\n    ),', '\n    ),');
}

String _models(Map<String, dynamic> data) {
  final b = StringBuffer(_header.replaceFirst('%s', 'models.json'))
    ..writeln("import 'schema.dart';")
    ..writeln()
    ..writeln('/// The GunsNPrices model dictionaries, one per brand.')
    ..writeln('const modelDicts = <ModelDict>[');
  for (final d in (data['dicts'] as List).cast<Map<String, dynamic>>()) {
    final terms = d['mode'] == 'terms';
    final f = <String>[
      'brand: ${_lit(d['brand'] as String)}',
      'terms: $terms',
      'brandWord: ${_lit(d['brand_word'] as String)}',
    ];
    void add(String name, String? code) {
      if (code != null) f.add('$name: $code');
    }

    final rx = d['brand_rx'] as String?;
    if (rx != null && rx.isNotEmpty) add('brandRx', _lit(rx));
    add('titleRewrite', _pairs(d['title_rewrite']));
    add('exclude', _list(d['exclude'], skipEmpty: true));
    add('excludeSoft', _list(d['exclude_soft'], skipEmpty: true));
    add('otherBrandBlock', _list(d['other_brand_block'], skipEmpty: true));
    add('otherBrandModels', _list(d['other_brand_models'], skipEmpty: true));
    if (terms) {
      add('termModels', _termModels(d['models'] as List<dynamic>));
    } else {
      add('numericModels', _strMap(d['models']));
    }
    add('configs', _pairs(d['configs']));
    add('features', _pairs(d['features']));
    add('gens', _pairs(d['gens']));
    add('featureOrder', _list(d['feature_order'], skipEmpty: true));
    add('brandNames', _list(d['brand_names'], skipEmpty: true));
    add('denyBrandNames', _list(d['deny_brand_names'], skipEmpty: true));
    add('familyDisplay', _strMap(d['family_display']));
    add('needed', _listMap(d['needed']));
    final implied = d['config_implied_by_gen_family'] as Map<String, dynamic>?;
    if (implied != null && implied.isNotEmpty) {
      add('configImpliedByGenFamily',
          '{${implied.entries.map((e) => '${_lit(e.key)}: ${_listMap(e.value) ?? '{}'}').join(', ')}}');
    }
    add('mpnLetterGen', _strMap(d['mpn_letter_gen']));
    add('mpnLetterModel', _strMap(d['mpn_letter_model']));
    add('mpnModelAlias', _strMap(d['mpn_model_alias']));
    add('noGenModels', _list(d['no_gen_models'], skipEmpty: true));
    add('bareModelTokens', _list(d['bare_model_tokens'], skipEmpty: true));
    b.writeln('  ModelDict(${f.join(', ')},),');
  }
  b.writeln('];');
  return b.toString();
}

String _termModels(List<dynamic> models) {
  final items = <String>[];
  for (final m in models.cast<Map<String, dynamic>>()) {
    final f = <String>[
      'name: ${_lit(m['name'] as String)}',
      'family: ${_lit(m['family'] as String)}',
      'match: ${_lit(m['match'] as String)}',
    ];
    final not = m['not'] as String?;
    if (not != null && not.isNotEmpty) f.add('notMatch: ${_lit(not)}');
    final configs = _list(m['configs'], skipEmpty: true);
    if (configs != null) f.add('configs: $configs');
    final implied = _list(m['implied_configs'], skipEmpty: true);
    if (implied != null) f.add('impliedConfigs: $implied');
    items.add('TermModel(${f.join(', ')},)');
  }
  return '[${items.join(', ')},]';
}

String _entities(Map<String, dynamic> data) {
  final b = StringBuffer(_header.replaceFirst('%s', 'entities.json'))
    ..writeln()
    ..writeln(
        '/// HTML5 named character references (Python html.entities.html5).')
    ..writeln('const html5Entities = <String, String>{');
  (data['html5'] as Map<String, dynamic>).forEach((k, v) {
    b.writeln('  ${_lit(k, ascii: true)}: ${_lit(v as String, ascii: true)},');
  });
  b
    ..writeln('};')
    ..writeln()
    ..writeln(
        '/// Numeric references replaced by html.unescape (Python _invalid_charrefs).')
    ..writeln('const invalidCharrefs = <int, String>{');
  (data['invalid_charrefs'] as Map<String, dynamic>).forEach((k, v) {
    b.writeln('  $k: ${_lit(v as String, ascii: true)},');
  });
  b
    ..writeln('};')
    ..writeln()
    ..writeln(
        '/// Code points dropped by html.unescape (Python _invalid_codepoints).')
    ..writeln('const invalidCodepoints = <int>{')
    ..writeln(
        '  ${(data['invalid_codepoints'] as List).map((n) => '0x${(n as int).toRadixString(16)}').join(', ')},')
    ..writeln('};');
  return b.toString();
}

String? _list(Object? v, {bool skipEmpty = false}) {
  final l = (v as List?)?.cast<String>() ?? const <String>[];
  if (skipEmpty && l.isEmpty) return null;
  return '[${l.map(_lit).join(', ')}]';
}

/// An ordered JSON object as a list of (key, value) records.
String? _pairs(Object? v) {
  final m = v as Map<String, dynamic>?;
  if (m == null || m.isEmpty) return null;
  return '[${m.entries.map((e) => '(${_lit(e.key)}, ${_lit(e.value as String)})').join(', ')}]';
}

String? _strMap(Object? v) {
  final m = v as Map<String, dynamic>?;
  if (m == null || m.isEmpty) return null;
  return '{${m.entries.map((e) => '${_lit(e.key)}: ${_lit(e.value as String)}').join(', ')}}';
}

String? _listMap(Object? v) {
  final m = v as Map<String, dynamic>?;
  if (m == null || m.isEmpty) return null;
  return '{${m.entries.map((e) => '${_lit(e.key)}: ${_list(e.value)}').join(', ')}}';
}

/// A Dart string literal: raw when that needs no escapes, escaped otherwise.
String _lit(String s, {bool ascii = false}) {
  bool plain(int r) => r >= 0x20 && r < 0x7f || (!ascii && r >= 0xa0);
  final printable = s.runes.every(plain);
  final special = s.contains(r'\') || s.contains(r'$');
  if (printable && !s.contains("'")) return special ? "r'$s'" : "'$s'";
  if (printable && !s.contains('"') && special) return 'r"$s"';
  final b = StringBuffer("'");
  for (final r in s.runes) {
    switch (r) {
      case 0x5c:
        b.write(r'\\');
      case 0x24:
        b.write(r'\$');
      case 0x27:
        b.write(r"\'");
      case 0x0a:
        b.write(r'\n');
      case 0x09:
        b.write(r'\t');
      case 0x0d:
        b.write(r'\r');
      default:
        b.write(plain(r)
            ? String.fromCharCode(r)
            : '\\u{${r.toRadixString(16).padLeft(4, '0')}}');
    }
  }
  b.write("'");
  return b.toString();
}
